"""Profile the 7 raw source CSVs and write docs/data_profile.md.

For each file: row count, columns + dtypes, null counts, min/max of date
columns, duplicate primary-key count and distinct year-months.
"""
from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
RAW = ROOT / "data" / "raw"
OUT = ROOT / "docs" / "data_profile.md"

FILES: dict[str, str] = {
    "01_master_data.csv": "MedicineID",
    "02_manufacturing_data.csv": "ManufacturingOrderID",
    "03_manufacturer_delivery_data.csv": "ShipmentID+ShipmentLineNumber",
    "04_warehouse_data.csv": "InventorySnapshotID",
    "05_pharmacy_sales_data.csv": "SalesTransactionID",
    "06_hospital_demand_data.csv": "HospitalDemandRecordID",
    "07_iot_streaming_data.csv": "SensorReadingID",
}


def is_date_col(name: str) -> bool:
    """Date/timestamp columns are identified by name suffix."""
    n = name.lower()
    return n.endswith("date") or n.endswith("month") or "timestamp" in n


def profile(fname: str, pk: str) -> str:
    df = pd.read_csv(RAW / fname, dtype=str, keep_default_na=False, na_values=[""])
    inferred = pd.read_csv(RAW / fname, nrows=5000).dtypes
    pk_cols = pk.split("+")
    dup = int(df.duplicated(subset=pk_cols).sum())
    lines = [f"## {fname}", "", f"- Rows: **{len(df):,}**", f"- Columns: {len(df.columns)}",
             f"- Primary key: `{pk}`; duplicate PK rows: **{dup}**", ""]
    lines += ["| column | inferred dtype | nulls | distinct | min | max |", "|---|---|---|---|---|---|"]
    for c in df.columns:
        s = df[c]
        nulls = int(s.isna().sum())
        mn = mx = ""
        if is_date_col(c):
            d = pd.to_datetime(s, errors="coerce", utc=True)
            if d.notna().any():
                mn, mx = str(d.min())[:19], str(d.max())[:19]
        elif str(inferred.get(c)) in ("int64", "float64"):
            num = pd.to_numeric(s, errors="coerce")
            mn, mx = f"{num.min():g}", f"{num.max():g}"
        lines.append(f"| {c} | {inferred.get(c)} | {nulls} | {s.nunique():,} | {mn} | {mx} |")
    for c in df.columns:
        if c in ("SalesDate", "DemandMonth", "SnapshotDate", "OrderDate", "DispatchDate", "EventTimestampUTC"):
            ym = pd.to_datetime(df[c], errors="coerce").dt.to_period("M")
            lines += ["", f"- `{c}` distinct year-months: **{ym.nunique()}** ({ym.min()} → {ym.max()})"]
    if fname.startswith("05"):
        for c in ("SalesChannel", "PharmacyType", "PayerType", "PaymentMethod", "CustomerSegment", "SaleStatus",
                  "PrescriptionRequiredFlag", "ReturnFlag", "EcommerceDeliveryStatus"):
            vc = df[c].value_counts(dropna=False).to_dict()
            lines.append(f"- `{c}` values: {vc}")
    if fname.startswith("06"):
        lines.append(f"- Hospitals: {df['HospitalID'].nunique()}, medicines: {df['MedicineID'].nunique()}, "
                     f"rows per month: {len(df) // max(1, pd.to_datetime(df['DemandMonth']).dt.to_period('M').nunique())}")
    if fname.startswith("01"):
        lines.append(f"- ColdChainFlag: {df['ColdChainFlag'].value_counts().to_dict()}; "
                     f"TherapeuticClass distinct: {df['TherapeuticClass'].nunique()}")
    lines.append("")
    print(f"profiled {fname}: {len(df):,} rows", file=sys.stderr)
    return "\n".join(lines)


def main() -> None:
    parts = ["# Source data profile", "", "Generated by `scripts/profile_data.py` from `data/raw/`.", ""]
    for f, pk in FILES.items():
        parts.append(profile(f, pk))
    OUT.write_text("\n".join(parts), encoding="utf-8")
    print(f"wrote {OUT}", file=sys.stderr)


if __name__ == "__main__":
    main()
